def box(flows, bg, border):
    t = Table([[flows]], colWidths=[W])
    t.setStyle(TableStyle([
        ("BACKGROUND", (0,0), (-1,-1), bg),
        ("BOX", (0,0), (-1,-1), 0.9, border),
        ("LEFTPADDING", (0,0), (-1,-1), 9), ("RIGHTPADDING", (0,0), (-1,-1), 9),
        ("TOPPADDING", (0,0), (-1,-1), 9), ("BOTTOMPADDING", (0,0), (-1,-1), 5),
        ("VALIGN", (0,0), (-1,-1), "TOP"),
    ]))
    return t

def table(rows, widths, header=True):
    data = [[Paragraph(c, cellb if (header and i == 0) else cell) for c in row] for i, row in enumerate(rows)]
    t = Table(data, colWidths=widths, repeatRows=1 if header else 0)
    st = [("VALIGN", (0,0), (-1,-1), "TOP"),
          ("LEFTPADDING", (0,0), (-1,-1), 6), ("RIGHTPADDING", (0,0), (-1,-1), 6),
          ("TOPPADDING", (0,0), (-1,-1), 5), ("BOTTOMPADDING", (0,0), (-1,-1), 5),
          ("LINEBELOW", (0,0), (-1,-2), 0.4, colors.HexColor("#d5dbe3")),
          ("BOX", (0,0), (-1,-1), 0.6, colors.HexColor("#c3ccd8"))]
    if header:
        st += [("BACKGROUND", (0,0), (-1,0), colors.HexColor("#eef2f7")),
               ("LINEBELOW", (0,0), (-1,0), 0.8, colors.HexColor("#9fb0c4"))]
    t.setStyle(TableStyle(st))
    return t

